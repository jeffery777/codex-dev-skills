"""Host-only, bounded Codex app-server stdio protocol primitive.

Trusted host code supplies argv, cwd, the COMPLETE child environment and fixed
callback. No loader, shell, credential adoption, production registry, sandbox
qualification or workflow is supplied. Method params/results need independent
parent validation. Notification names follow public CLI 0.159.3 generated schema;
accepting a notification never authorizes an action. Payloads stay in memory and
are never copied into diagnostics. Stderr is discarded.

A callback must itself be bounded trusted code: this synchronous primitive cannot
interrupt Python callbacks. Any protocol/IO/callback uncertainty latches UNKNOWN;
there is no retry, relaunch, kill, or descendant-stop claim. close() only closes
pipes and observes the direct child for a bounded interval.
"""
